_BUILTIN_PROMPTS: dict[str, str] = {
    AgentPromptSlot.KB_ANSWER: _KB_ANSWER_PROMPT,
    AgentPromptSlot.MCP_ANSWER: _MCP_ANSWER_PROMPT,
    AgentPromptSlot.MIXED_ANSWER: _MIXED_ANSWER_PROMPT,
}


def _default_for_scene(scene: PromptScene) -> str:
    """空场景用 KB 基线；与 ragent 行为一致：EMPTY 时上层不调用 build。"""
    return _BUILTIN_PROMPTS[AgentPromptSlot.KB_ANSWER]


class AgentPromptResolver:
    """严格对应 ragent rag.core.prompt.AgentPromptResolver。

    ragent 行为：
      1. 优先读 AgentProfileDO.builtin 槽位作为基线
      2. 再叠加 AgentProfileDO.active 槽位（非空才覆盖）
      3. resolveAll 缓存
    当前 Python 版（无 DB）：用内置常量作"builtin"，无"active"叠加层。
    """

    def __init__(self) -> None:
        self._cache: dict[str, str] | None = None

    def _resolve_all(self) -> dict[str, str]:
        if self._cache is None:
            self._cache = dict(_BUILTIN_PROMPTS)
        return self._cache

    def resolve(self, slot: str) -> str:
        """严格对应 ragent AgentPromptResolver.resolve(slot)：缺槽位返回空串。"""
        if not slot:
            return ""
        return self._resolve_all().get(slot, "")

    def render(self, slot: str, slots: dict[str, Any] | None = None) -> str:
        from core.prompt.template_loader import cleanup_prompt, fill_slots
        return cleanup_prompt(fill_slots(self.resolve(slot), slots))

    def default_for_scene(self, scene: PromptScene) -> str:
        """空场景基线：与 ragent `RAGPromptService.plan` 的 empty 分支一致。"""
        return _default_for_scene(scene)
